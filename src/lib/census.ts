export interface Aggregate {
  name: string;
  districts: number;
  population: number;
  male: number;
  female: number;
  literate: number;
  workers: number;
  households: number;
  urbanHouseholds: number;
  electrifiedHouseholds: number;
  internetHouseholds: number;
}

function sum(ds: District[], name: string): Aggregate {
  const a: Aggregate = {
    name,
    districts: ds.length,
    population: 0, male: 0, female: 0, literate: 0, workers: 0,
    households: 0, urbanHouseholds: 0, electrifiedHouseholds: 0, internetHouseholds: 0,
  };
  for (const d of ds) {
    a.population += d.population;
    a.male += d.male;
    a.female += d.female;
    a.literate += d.literate;
    a.workers += d.workers;
    a.households += d.households;
    a.urbanHouseholds += d.urbanHouseholds;
    a.electrifiedHouseholds += d.electrifiedHouseholds;
    a.internetHouseholds += d.internetHouseholds;
  }
  return a;
}

export const INDIA: Aggregate = sum(DISTRICTS, "India");

export const STATE_TOTALS: Record<string, Aggregate> = Object.fromEntries(
  STATES.map((s) => [s, sum(DISTRICTS.filter((d) => d.state === s), s)]),
);

/**
 * The same seven measures, read off an aggregate rather than a district.
 * A rate over a state is the state's own ratio, not the mean of its
 * districts' ratios, which would weight a tiny district like a huge one.
 */
export function aggregateValue(a: Aggregate, key: MetricKey): number {
  switch (key) {
    case "population": return a.population / a.districts;
    case "sexRatio": return (a.female / a.male) * 1000;
    case "literateShare": return (a.literate / a.population) * 100;
    case "urbanShare": return (a.urbanHouseholds / a.households) * 100;
    case "electrified": return (a.electrifiedHouseholds / a.households) * 100;
    case "internet": return (a.internetHouseholds / a.households) * 100;
    case "workerShare": return (a.workers / a.population) * 100;
  }
}

/**
 * What a district is compared against. Population is a count, so comparing one
 * district with a national total would only ever say "much smaller"; there the
 * comparison is the average district. Every other measure is a ratio, so the
 * aggregate's own ratio is the right benchmark.
 */
export function comparator(a: Aggregate, key: MetricKey) {
  return {
    value: aggregateValue(a, key),
    label: key === "population" ? `the average ${a.name} district` : a.name,
  };
}

export function rangeOf(key: MetricKey, ds: District[] = DISTRICTS) {
  const m = METRIC_BY_KEY[key];
  const vals = ds.map((d) => m.value(d));
  return { min: Math.min(...vals), max: Math.max(...vals) };
}

export function rankOf(d: District, key: MetricKey, within: District[] = DISTRICTS) {
  const m = METRIC_BY_KEY[key];
  const sorted = [...within].sort((x, y) => m.value(y) - m.value(x));
  return { rank: sorted.findIndex((x) => x.id === d.id) + 1, of: sorted.length };
}
